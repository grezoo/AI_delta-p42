    def run_dvp13_benchmark(
        self,
        n_trials: int = 1000,
        seed: int = 42,
    ) -> Dict[str, Any]:
        """
        Executes the formal DVP-13 quantitative benchmark:
        - Evaluates n_trials candidate batches (K in [5, 20]).
        - Evaluates diverse Maslow vacuum vectors V in [0, 1]^5.
        - Verifies that decision mismatch rate against analytical ground-truth is < 0.1% (< 1 error per 1000).
        - Verifies that zero decision deadlock / floating occurs.

        Returns:
            Dict containing:
                passed: bool
                total_evaluations: int
                mismatch_count: int
                mismatch_rate: float
                mismatch_threshold: float (0.001)
                zero_deadlock_verified: bool
        """
        rng = np.random.RandomState(seed)
        mismatch_count = 0
        deadlock_count = 0

        for trial in range(n_trials):
            # Batch size K between 5 and 20
            k_cand = rng.randint(5, 21)

            # Generate candidates
            candidates: List[GoalCandidate] = []
            for c_idx in range(k_cand):
                emb = rng.randn(self.d_embed)
                # Normalize embedding
                norm = np.linalg.norm(emb)
                if norm > 1e-9:
                    emb = emb / norm
                cand = GoalCandidate(
                    candidate_id=f"cand_trial_{trial}_{c_idx}",
                    concept=f"concept_{trial}_{c_idx}",
                    embedding=emb,
                )
                candidates.append(cand)

            # Generate diverse Maslow deficit vector V in [0, 1]^5
            # Include varying deficit profiles: sparse, concentrated, uniform, saturated
            v_profile = rng.rand(MASLOW_DRIVE_COUNT)
            # Ensure at least one drive has some activity
            if np.max(v_profile) < 0.1:
                v_profile[rng.randint(0, MASLOW_DRIVE_COUNT)] = 0.85

            # Ground-truth analytical calculation:
            embeddings_mat = np.stack([c.embedding for c in candidates])  # (K, d_embed)
            true_resonances = np.dot(embeddings_mat, np.dot(self._w_pfc, v_profile))  # (K,)
            k_star_true = int(np.argmax(true_resonances))
            rho_max_true = float(true_resonances[k_star_true])

            # Run PFC evaluation
            goal = self.evaluate_candidates(candidates, v_profile, timestamp_ns=1000000 + trial)

            # Verification of decision correctness:
            if rho_max_true > self.rho_threshold:
                if goal is None:
                    # Mismatch: should have formed goal, but returned None
                    mismatch_count += 1
                elif goal.candidate_id != candidates[k_star_true].candidate_id:
                    # Check for float precision tie:
                    res_diff = abs(goal.resonance - rho_max_true)
                    if res_diff > 1e-9:
                        mismatch_count += 1
                elif not (0.0 <= goal.priority <= 1.0):
                    deadlock_count += 1
            else:
                if goal is not None:
                    # Mismatch: should have decayed to quiescence, but formed goal
                    mismatch_count += 1

        mismatch_rate = mismatch_count / float(n_trials)
        passed = (mismatch_count == 0) and (deadlock_count == 0) and (mismatch_rate < 0.001)

        return {
            "passed": passed,
            "total_evaluations": n_trials,
            "mismatch_count": mismatch_count,
            "mismatch_rate": mismatch_rate,
            "mismatch_threshold": 0.001,
            "zero_deadlock_verified": (deadlock_count == 0),
        }

