@dataclass(frozen=True)
class GoalCandidate:
    """
    An association candidate generated by the conceptual thought stream / Chorus LLM.

    Attributes:
        candidate_id: Unique string identifier for the candidate.
        concept: Symbolic phrase or natural language concept (e.g. 'szép a felhő').
        embedding: Semantic embedding vector w_k in R^(d_embed).
    """
    candidate_id: str
    concept: str
    embedding: np.ndarray

    def __post_init__(self) -> None:
        if not isinstance(self.candidate_id, str) or not self.candidate_id:
            raise ValueError("candidate_id must be a non-empty string")
        if not isinstance(self.concept, str):
            raise ValueError("concept must be a string")
        arr = np.asarray(self.embedding, dtype=np.float64)
        if arr.ndim != 1:
            arr = arr.flatten()
        if not np.all(np.isfinite(arr)):
            raise ValueError("Candidate embedding contains non-finite values (NaN or Inf)")
        # Object is frozen, assign via object.__setattr__
        object.__setattr__(self, "embedding", arr)


@dataclass(frozen=True)
class GoalStructure:
    """
    Active goal structure instantiated by the Prefrontal Cortex (T_goal).

    Attributes:
        goal_uuid: RFC-4122 v4 unique identifier string.
        candidate_id: Reference ID of the originating GoalCandidate.
        concept: Conceptual description of the selected goal.
        priority: Priority scalar in [0.0, 1.0], derived from resonance.
        resonance: Measured scalar resonance score rho_max.
        dominant_need_idx: Index of dominant Maslow deficit (0..4).
        intent_vector: Action intent proposal u_intent in R^(d_action) for Basal Ganglia.
        predictive_state: Top-down predictive sensory expectation c_pred in R^(d_sens).
        timestamp_ns: Nanosecond timestamp of goal creation.
        subtasks: Hierarchical decomposition plan tree.
    """
    goal_uuid: str
    candidate_id: str
    concept: str
    priority: float
    resonance: float
    dominant_need_idx: int
    intent_vector: np.ndarray
    predictive_state: np.ndarray
    timestamp_ns: int
    subtasks: Tuple[str, ...] = field(default_factory=tuple)

    def __post_init__(self) -> None:
        if not (0.0 <= self.priority <= 1.0):
            raise ValueError(f"Priority must be in [0.0, 1.0], got {self.priority}")
        if not (0 <= self.dominant_need_idx < MASLOW_DRIVE_COUNT):
            raise ValueError(f"dominant_need_idx must be in 0..{MASLOW_DRIVE_COUNT-1}")
        if not np.all(np.isfinite(self.intent_vector)):
            raise ValueError("intent_vector contains non-finite values")
        if not np.all(np.isfinite(self.predictive_state)):
            raise ValueError("predictive_state contains non-finite values")


class PFCExecutive:
    """
    Prefrontal Cortex Goal Selection & Executive Focus Engine.
    Implements the Airplane Principle (Repülőgép-elv) mathematical model:
        rho_k = w_(assoc, k)^T * W_PFC * V(t)
    When max_k rho_k > rho_threshold, instantiates GoalStructure and generates
    top-down predictive mental image c_pred and action intent u_intent.
    """

    def __init__(
        self,
        d_embed: int = DEFAULT_D_EMBED,
        d_sens: int = DEFAULT_D_SENS,
        d_action: int = DEFAULT_D_ACTION,
        rho_threshold: float = RHO_THRESHOLD_CANONICAL,
        w_pfc: Optional[np.ndarray] = None,
        w_action: Optional[np.ndarray] = None,
        w_sens: Optional[np.ndarray] = None,
        seed: Optional[int] = 42,
    ) -> None:
        self.d_embed = int(d_embed)
        self.d_sens = int(d_sens)
        self.d_action = int(d_action)
        self.rho_threshold = float(rho_threshold)
        self.seed = seed

        rng = np.random.RandomState(seed if seed is not None else 42)

        # 1. Semantic-to-Drive Projection Matrix W_PFC in R^(d_embed x 5)
        if w_pfc is not None:
            arr_pfc = np.asarray(w_pfc, dtype=np.float64)
            if arr_pfc.shape != (self.d_embed, MASLOW_DRIVE_COUNT):
                raise ValueError(
                    f"w_pfc shape mismatch: expected ({self.d_embed}, {MASLOW_DRIVE_COUNT}), got {arr_pfc.shape}"
                )
            if not np.all(np.isfinite(arr_pfc)):
                raise ValueError("w_pfc contains non-finite values")
            self._w_pfc = arr_pfc.copy()
        else:
            # Calibrated semi-orthogonal Gaussian projection into 5 Maslow drives
            raw_w = rng.randn(self.d_embed, MASLOW_DRIVE_COUNT)
            col_norms = np.linalg.norm(raw_w, axis=0, keepdims=True)
            col_norms[col_norms == 0.0] = 1.0
            self._w_pfc = (raw_w / col_norms * (1.0 / np.sqrt(MASLOW_DRIVE_COUNT)) * 2.0).astype(np.float64)

        # 2. Action Intent Projection Matrix W_action in R^(d_action x d_embed)
        if w_action is not None:
            arr_act = np.asarray(w_action, dtype=np.float64)
            if arr_act.shape != (self.d_action, self.d_embed):
                raise ValueError(f"w_action shape mismatch: expected ({self.d_action}, {self.d_embed})")
            self._w_action = arr_act.copy()
        else:
            self._w_action = (rng.randn(self.d_action, self.d_embed) / np.sqrt(self.d_embed)).astype(np.float64)

        # 3. Sensory Mental Image Projection Matrix W_sens in R^(d_sens x d_embed)
        if w_sens is not None:
            arr_sens = np.asarray(w_sens, dtype=np.float64)
            if arr_sens.shape != (self.d_sens, self.d_embed):
                raise ValueError(f"w_sens shape mismatch: expected ({self.d_sens}, {self.d_embed})")
            self._w_sens = arr_sens.copy()
        else:
            self._w_sens = (rng.randn(self.d_sens, self.d_embed) / np.sqrt(self.d_embed)).astype(np.float64)

        # Runtime State & Telemetry
        self._active_goal: Optional[GoalStructure] = None
        self._total_evaluations: int = 0
        self._goals_created: int = 0
        self._quiescent_cycles: int = 0

    @property
    def w_pfc(self) -> np.ndarray:
        """Returns a copy of the semantic-to-drive projection matrix."""
        return self._w_pfc.copy()

    @property
    def active_goal(self) -> Optional[GoalStructure]:
        """Returns the currently active GoalStructure, or None if quiescent."""
        return self._active_goal

    def compute_resonances(
        self,
        candidates: Sequence[GoalCandidate],
        maslow_vector: Union[np.ndarray, Sequence[float]],
    ) -> np.ndarray:
        """
        Computes the scalar resonance scores rho_k for all candidate thoughts:
            rho_k = w_(assoc, k)^T * W_PFC * V(t)

        Args:
            candidates: Sequence of GoalCandidate objects (length K > 0).
            maslow_vector: Maslow deficit vector V in [0, 1]^5.

        Returns:
            np.ndarray of shape (K,), dtype float64 with resonance scores.

        Raises:
            ValueError: If candidates is empty, or inputs contain NaN/Inf or shape mismatches.
        """
        if not candidates:
            raise ValueError("candidates sequence cannot be empty")

        v = np.asarray(maslow_vector, dtype=np.float64)
        if v.ndim != 1 or v.shape[0] != MASLOW_DRIVE_COUNT:
            raise ValueError(
                f"Maslow vector must have shape ({MASLOW_DRIVE_COUNT},), got {v.shape}"
            )
        if not np.all(np.isfinite(v)):
            raise ValueError("Maslow vector contains non-finite values (NaN or Inf)")

        # Stack candidate embeddings into matrix W_cand in R^(K x d_embed)
        k_count = len(candidates)
        embeddings = np.zeros((k_count, self.d_embed), dtype=np.float64)
        for i, cand in enumerate(candidates):
            emb = cand.embedding
            if emb.shape[0] != self.d_embed:
                raise ValueError(
                    f"Candidate {cand.candidate_id} embedding dimension {emb.shape[0]} != {self.d_embed}"
                )
            embeddings[i, :] = emb

        # Matrix projection: rho = W_cand * W_PFC * V
        # W_PFC * V is in R^(d_embed)
        projected_drive = np.dot(self._w_pfc, v)  # shape (d_embed,)
        resonances = np.dot(embeddings, projected_drive)  # shape (K,)

        return resonances

    def evaluate_candidates(
        self,
        candidates: Sequence[GoalCandidate],
        maslow_vector: Union[np.ndarray, Sequence[float]],
        timestamp_ns: Optional[int] = None,
        x_ext: Optional[np.ndarray] = None,
    ) -> Optional[GoalStructure]:
        """
        Evaluates candidate concepts against the Maslow vacuum vector using the
        Airplane Principle. Deterministically selects the dominant goal k* = argmax_k rho_k.

        If max_k rho_k > rho_threshold, instantiates and returns a new GoalStructure.
        If max_k rho_k <= rho_threshold, the thought decays into quiescence (returns None).

        Args:
            candidates: Sequence of GoalCandidate objects.
            maslow_vector: Current Maslow deficit vector V(t).
            timestamp_ns: Optional nanosecond timestamp. If None, time.perf_counter_ns() is used.
            x_ext: Optional external sensory context vector in R^(d_sens).

        Returns:
            Optional[GoalStructure]: Active goal or None.
        """
        self._total_evaluations += 1
        t_ns = timestamp_ns if timestamp_ns is not None else time.perf_counter_ns()

        resonances = self.compute_resonances(candidates, maslow_vector)
        v = np.asarray(maslow_vector, dtype=np.float64)

        # Deterministic dominant selection with index-based tie breaking
        # np.argmax returns the first occurrence of the maximum value
        k_star = int(np.argmax(resonances))
        rho_max = float(resonances[k_star])

        # Threshold Gating:
        if rho_max <= self.rho_threshold:
            # Thought decays into quiescence
            self._quiescent_cycles += 1
            self._active_goal = None
            return None

        # Goal instantiation
        winner = candidates[k_star]
        priority = float(np.clip(rho_max, 0.0, 1.0))
        dominant_need_idx = int(np.argmax(v))

        # Synthesize motor action intent and top-down sensory prediction
        u_intent, c_pred = self.synthesize_intent_and_prediction(winner.embedding, x_ext=x_ext)

        # Plan tree decomposition
        subtasks = self.generate_plan_tree(winner.concept, dominant_need_idx)

        goal = GoalStructure(
            goal_uuid=str(uuid.uuid4()),
            candidate_id=winner.candidate_id,
            concept=winner.concept,
            priority=priority,
            resonance=rho_max,
            dominant_need_idx=dominant_need_idx,
            intent_vector=u_intent,
            predictive_state=c_pred,
            timestamp_ns=t_ns,
            subtasks=subtasks,
        )

        self._goals_created += 1
        self._active_goal = goal
        return goal

    def synthesize_intent_and_prediction(
        self,
        embedding: np.ndarray,
        x_ext: Optional[np.ndarray] = None,
    ) -> Tuple[np.ndarray, np.ndarray]:
        """
        Synthesizes action intent u_intent in R^(d_action) and predictive sensory
        mental image c_pred in R^(d_sens) from the winning concept embedding.

        u_intent = tanh(W_action * w)
        c_pred   = sigmoid(W_sens * w + (0.2 * x_ext if provided))
        """
        w = np.asarray(embedding, dtype=np.float64)
        if w.ndim != 1 or w.shape[0] != self.d_embed:
            w = w.flatten()[: self.d_embed]

        # Action intent in [-1.0, 1.0]
        u_intent = np.tanh(np.dot(self._w_action, w)).astype(np.float32)

        # Sensory prediction in [0.0, 1.0]
        raw_sens = np.dot(self._w_sens, w)
        if x_ext is not None:
            x_arr = np.asarray(x_ext, dtype=np.float64).flatten()
            overlap = min(x_arr.size, self.d_sens)
            raw_sens[:overlap] += 0.2 * x_arr[:overlap]

        # Sigmoid transfer function
        c_pred = (1.0 / (1.0 + np.exp(-np.clip(raw_sens, -30.0, 30.0)))).astype(np.float32)

        return u_intent, c_pred

